// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other rankable pre-token protocol in the snapshot: the early rows the radar exists to find. A
// protocol is pre-token when its record carries no token (no market cap, no CoinGecko id, no
// symbol); live-token protocols are kept apart and shown with the market's own values, never mixed
// into the ranked board.
//
// Implied value follows only from the snapshot's own figures, in four factors:
//
//   multiple   = the market's own price for this kind of protocol: the median market-cap / TVL of
//                the live-token protocols in the same category (at least 3 comparables), else the
//                median across all live-token protocols; clamped to [0.05, 0.80].
//   growth     = clamp(change_7d, -60, 120) per cent; rises add half their weight, falls add three
//                quarters: a shrinking protocol's launch is worth less than a growing one's.
//   maturity   = 0.6 + min(age_days, 1825) / 1825 x 0.4   (age_days unknown: 365)
//   chains     = 1 + 0.03 x min(chains - 1, 5): a launch reaches further on more chains.
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturityMult x chainMult))
//
// The multiples are computed from the snapshot at run time, never written down per protocol: the
// same function scores every row, and no protocol name is ever special-cased.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

